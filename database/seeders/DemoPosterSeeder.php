<?php

namespace Database\Seeders;

use App\Models\Poster;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\Storage;

/**
 * Placeholder posters so the display can be demoed without a media server.
 *
 *   php artisan migrate
 *   php artisan db:seed --class=DemoPosterSeeder
 *
 * Rows use source "demo" (not an enabled source, so syncs never touch them).
 * Remove them again with:
 *   php artisan tinker --execute="App\Models\Poster::where('source','demo')->delete()"
 * and delete storage/app/posters/demo.
 */
class DemoPosterSeeder extends Seeder
{
    private const TITLES = [
        ['The Midnight Projector', 1954, 'G', '#8c1c13'],
        ['Velvet Curtain', 1962, 'PG', '#1b4965'],
        ['Return of the Usher', 1977, 'PG', '#3a5a40'],
        ['Popcorn Nebula', 1982, 'PG-13', '#5f0f40'],
        ['Reel to Reel', 1989, 'PG-13', '#9a031e'],
        ['The Last Matinee', 1994, 'R', '#283618'],
        ['Silver Screen Heist', 2001, 'PG-13', '#14213d'],
        ['Intermission', 2008, 'PG', '#6a040f'],
        ['Ticket Stub', 2013, 'G', '#0b525b'],
        ['Surround Sound', 2017, 'PG-13', '#3c096c'],
        ['Coming Attractions', 2021, 'PG', '#7f4f24'],
        ['Final Credits', 2025, 'R', '#212529'],
    ];

    public function run(): void
    {
        $disk = Storage::disk(config('posters.images.disk', 'posters'));
        $gd = function_exists('imagecreatetruecolor') && function_exists('imagepng');

        if (! $gd) {
            $this->command?->warn('GD is not available: demo posters are created without images and will not be displayed.');
        }

        foreach (self::TITLES as $i => [$title, $year, $rating, $colour]) {
            $id = sprintf('demo-%02d', $i + 1);
            $tag = sha1($id.$colour);
            $image = [];

            if ($gd) {
                $bytes = $this->render($title, $year, $colour);
                $path = sprintf('demo/%s/%s-%s.png', substr(sha1($id), 0, 2), $id, substr(sha1($tag), 0, 12));
                $disk->put($path, $bytes);

                $image = [
                    'image_tag' => $tag,
                    'image_path' => $path,
                    'image_mime' => 'image/png',
                    'image_width' => 1000,
                    'image_height' => 1500,
                ];
            }

            Poster::updateOrCreate(
                ['source' => 'demo', 'source_item_id' => $id],
                [
                    'media_type' => 'movie',
                    'title' => $title,
                    'sort_title' => $title,
                    'year' => $year,
                    'overview' => 'A placeholder poster generated by DemoPosterSeeder.',
                    'official_rating' => $rating,
                    'community_rating' => round(5 + ($i % 5), 1),
                    'runtime_minutes' => 90 + $i * 5,
                    'genres' => ['Demo'],
                    'library_name' => 'Demo',
                    'is_active' => true,
                    'missed_syncs' => 0,
                    'last_seen_at' => now(),
                    'extra' => ['demo' => true],
                    ...$image,
                ],
            );
        }

        $this->command?->info('Seeded '.count(self::TITLES).' demo posters.');
    }

    private function render(string $title, int $year, string $hex): string
    {
        $w = 1000;
        $h = 1500;
        $img = imagecreatetruecolor($w, $h);

        [$r, $g, $b] = sscanf($hex, '#%02x%02x%02x');
        imagefilledrectangle($img, 0, 0, $w, $h, imagecolorallocate($img, $r, $g, $b));

        // Darker band + frame so it reads as a "poster".
        $dark = imagecolorallocate($img, (int) ($r * 0.4), (int) ($g * 0.4), (int) ($b * 0.4));
        imagefilledrectangle($img, 0, (int) ($h * 0.62), $w, (int) ($h * 0.82), $dark);
        $light = imagecolorallocate($img, 240, 230, 200);
        imagesetthickness($img, 12);
        imagerectangle($img, 40, 40, $w - 41, $h - 41, $light);

        // Built-in bitmap font, scaled up for legibility.
        $this->bigText($img, strtoupper($title), (int) ($h * 0.66), 6, $light, $w);
        $this->bigText($img, (string) $year, (int) ($h * 0.75), 5, $light, $w);

        ob_start();
        imagepng($img);
        $bytes = (string) ob_get_clean();
        unset($img);

        return $bytes;
    }

    /** Draw built-in font 5 text, scaled by $scale, centred horizontally. */
    private function bigText(\GdImage $img, string $text, int $y, int $scale, int $colour, int $width): void
    {
        $font = 5;
        $tw = imagefontwidth($font) * strlen($text);
        $th = imagefontheight($font);

        while ($tw * $scale > $width - 120 && $scale > 1) {
            $scale--;
        }

        $tmp = imagecreatetruecolor($tw, $th);
        imagealphablending($tmp, false);
        $transparent = imagecolorallocatealpha($tmp, 0, 0, 0, 127);
        imagefilledrectangle($tmp, 0, 0, $tw, $th, $transparent);
        imagesavealpha($tmp, true);
        imagestring($tmp, $font, 0, 0, $text, $colour);

        imagealphablending($img, true);
        imagecopyresized($img, $tmp, (int) (($width - $tw * $scale) / 2), $y, 0, 0, $tw * $scale, $th * $scale, $tw, $th);
        unset($tmp);
    }
}
